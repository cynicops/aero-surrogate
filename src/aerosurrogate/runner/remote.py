"""Remote execution: SSH (rsync + ssh) and SLURM (sbatch).

UNTESTED: no remote host or cluster is reachable from the cloud workspace. Only command
construction and script rendering are unit-tested. On a cluster, prefer preparing cases
locally (mesh + case files) and submitting `slurm_script` per case.
"""

from __future__ import annotations

import shlex
import subprocess
from dataclasses import dataclass
from pathlib import Path

UNTESTED = True


@dataclass
class SSHConfig:
    host: str  # e.g. "user@workstation"
    remote_root: str  # absolute path on the remote machine
    bashrc: str = "/usr/lib/openfoam/openfoam2512/etc/bashrc"
    n_procs: int = 4
    ssh_options: tuple[str, ...] = ("-o", "BatchMode=yes")


def ssh_commands(case_dir: str | Path, cfg: SSHConfig) -> list[list[str]]:
    """UNTESTED. The three commands: push case, run Allrun remotely, pull results back."""
    case_dir = Path(case_dir).resolve()
    remote = f"{cfg.remote_root.rstrip('/')}/{case_dir.name}"
    run = (f"source {shlex.quote(cfg.bashrc)} >/dev/null 2>&1; cd {shlex.quote(remote)} && bash Allrun")
    return [
        ["rsync", "-az", "-e", "ssh " + " ".join(cfg.ssh_options), f"{case_dir}/", f"{cfg.host}:{remote}/"],
        ["ssh", *cfg.ssh_options, cfg.host, run],
        ["rsync", "-az", "-e", "ssh " + " ".join(cfg.ssh_options), f"{cfg.host}:{remote}/", f"{case_dir}/"],
    ]


def allrun_script(n_procs: int, max_iter_note: str = "") -> str:
    """Plain-shell pipeline equivalent to runner.local (without live force monitoring:
    rely on residualControl and endTime). Used by SSH and SLURM jobs."""
    par = f"decomposePar -force > log.decomposePar 2>&1\nmpirun -np {n_procs} simpleFoam -parallel > log.simpleFoam 2>&1\nreconstructPar -latestTime > log.reconstructPar 2>&1" if n_procs > 1 else "simpleFoam > log.simpleFoam 2>&1"
    return f"""#!/bin/bash
# Generated by aerosurrogate. {max_iter_note}
set -e
gmshToFoam mesh.msh > log.gmshToFoam 2>&1
# NOTE: patch types must already be set (run `aerosurrogate` locally up to the mesh step), or
# edit constant/polyMesh/boundary here.
checkMesh > log.checkMesh 2>&1
{par}
"""


@dataclass
class SlurmConfig:
    partition: str = "compute"
    n_procs: int = 4
    time: str = "02:00:00"
    mem: str = "4G"
    bashrc: str = "/usr/lib/openfoam/openfoam2512/etc/bashrc"
    account: str | None = None
    modules: tuple[str, ...] = ()


def slurm_script(case_dir: str | Path, job_name: str, cfg: SlurmConfig) -> str:
    """UNTESTED on a real scheduler. Returns an sbatch script that runs one case."""
    case_dir = Path(case_dir).resolve()
    lines = [
        "#!/bin/bash",
        f"#SBATCH --job-name={job_name}",
        f"#SBATCH --partition={cfg.partition}",
        f"#SBATCH --ntasks={cfg.n_procs}",
        f"#SBATCH --time={cfg.time}",
        f"#SBATCH --mem={cfg.mem}",
        f"#SBATCH --output={case_dir}/slurm-%j.out",
    ]
    if cfg.account:
        lines.append(f"#SBATCH --account={cfg.account}")
    lines += [f"module load {m}" for m in cfg.modules]
    lines += [f"source {shlex.quote(cfg.bashrc)}", f"cd {shlex.quote(str(case_dir))}", "bash Allrun", ""]
    return "\n".join(lines)


def submit_slurm(script_path: str | Path) -> str:
    """UNTESTED. Submit with sbatch and return the job id."""
    out = subprocess.run(["sbatch", "--parsable", str(script_path)], capture_output=True, text=True, check=True)
    return out.stdout.strip().split(";")[0]
